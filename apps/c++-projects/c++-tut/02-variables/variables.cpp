#include <iostream>

int main() {

    int x = 10;
    int y = 5;
    int sum = x + y;

    std::cout << x << '\n';
    std::cout << y << '\n';
    std::cout << sum << "\n";

    //double (including decimal)
    double price = 10.56;

    std::cout << price << '\n';

    //char (single character)
    char a = 'a';
    char b = 'b';
    char endline = '\n';

    std::cout << a << b << endline;

    //boolean 
    bool money = true; // 1

    std::cout << money << '\n';

    // string 
    std::string name = "Antonio";

    std::cout << name << '\n';
    

    return 0;
}